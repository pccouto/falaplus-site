import { mkdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { SERIES, COPY, getPracticalAppArticle } from '../_fonte/artigos/app-pratica-data.mjs'
import { CATALOG } from '../_fonte/artigos/catalogo.mjs'

for (const item of SERIES) for (const lang of Object.keys(COPY)) {
  const a = getPracticalAppArticle(item, lang)
  for (const b of a.blocks) if (b.p) b.p = b.p.replace(/\[\[([^|]+)\|[^\]]+\]\]/g, (match, id) => {
    const related = CATALOG.find(entry => entry.id === id)?.[lang]
    if (!related) throw new Error(`Unknown related article: ${lang}/${id}`)
    return `[[${id}|${related.title}]]`
  })
  const dir = new URL(`../_fonte/artigos/conteudo/${lang}/`, import.meta.url)
  mkdirSync(dir, { recursive: true })
  writeFileSync(fileURLToPath(new URL(`${a.slug}.mjs`, dir)), `// Generated by scripts/build-practical-app-articles.mjs\nexport default ${JSON.stringify(a, null, 2)}\n`)
}
console.log(`${SERIES.length * 3} practical app article sources generated.`)
